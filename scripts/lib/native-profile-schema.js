import { stripComments, literal, balanced, split, functionBlock, lineAt, enumMaps, metadataBlock, dependencyReferences, positiveValidationRules } from './native-schema.js';

function stringList(source, name) {
  const match = source.match(new RegExp(`\\b${name}\\s*(?:=\\s*)?\\{`));
  if (!match) throw new Error(`Missing native membership: ${name}`);
  const keys = split(balanced(source, match.index + match[0].lastIndexOf('{')).text).map(item => literal(item));
  if (keys.some(key => typeof key !== 'string')) throw new Error(`Unresolved native membership: ${name}`);
  return keys;
}

function definitionsFrom(cleaned) {
  const constants = {};
  for (const match of cleaned['PrintConfigConstants.hpp'].matchAll(/^\s*#define\s+(\w+)\s+([^\n]+)/gm)) constants[match[1]] = literal(match[2]);
  for (const match of cleaned['PrintConfig.cpp'].matchAll(/\bconst\s+(?:int|double|float|bool)\s+(\w+)\s*=\s*([^;]+);/g)) {
    const value = literal(match[2], constants);
    if (typeof value !== 'object') constants[match[1]] = value;
  }
  const context = { constants, aliases: {}, enums: enumMaps(cleaned['PrintConfig.cpp']) };
  const source = cleaned['PrintConfig.cpp'], definitions = new Map();
  for (const signature of ['void PrintConfigDef::init_common_params()', 'void PrintConfigDef::init_fff_params()']) {
    const block = functionBlock(source, signature);
    const calls = [...block.text.matchAll(/\bdef\s*=\s*this->add(?:_nullable)?\s*\(/g)];
    for (let index = 0; index < calls.length; index++) {
      const match = calls[index], call = balanced(block.text, match.index + match[0].lastIndexOf('(')), args = split(call.text), key = literal(args[0]);
      if (typeof key !== 'string' || !/^co\w+$/.test(args[1] || '')) continue;
      const body = block.text.slice(call.end, calls[index + 1]?.index ?? block.text.length);
      const { definition, raw } = metadataBlock(body, key, args[1], context);
      definition.source = { file: 'PrintConfig.cpp', line: lineAt(source, block.start + match.index) };
      const alias = block.text.slice(block.text.lastIndexOf('\n', match.index) + 1, match.index).match(/auto\s+(\w+)\s*=\s*$/)?.[1];
      if (alias) context.aliases[alias] = raw;
      const defaultExpression = body.match(/def->set_default_value\s*\(/);
      if (defaultExpression) {
        const expression = balanced(body, defaultExpression.index + defaultExpression[0].lastIndexOf('(')).text;
        if (/ConfigOption\w+Nullable/.test(expression)) definition.nullable = true;
        if (Array.isArray(definition.default) && definition.default.length === 1 && Array.isArray(definition.default[0])) definition.default = definition.default[0];
        if (definition.default?.unresolved || definition.unresolved.some(item => item.field === 'default')) {
          let replacement;
          if (/^new ConfigOptionEnum/.test(expression.trim())) {
            const enumType = body.match(/enum_keys_map\s*=\s*&ConfigOptionEnum<([^>]+)>/)?.[1];
            const constructor = expression.match(/^new\s+ConfigOption\w+(?:<[^>]+>)?\s*([({])/);
            if (constructor && enumType) {
              let values = balanced(expression, expression.indexOf(constructor[1])).text.trim();
              if (values.startsWith('{')) values = values.slice(1, -1);
              const symbols = split(values).map(symbol => symbol.replace(/\(int\)/g, '').replace(/\s+/g, '').split('::').at(-1));
              const mapped = symbols.map(symbol => context.enums[enumType]?.find(item => item.symbol.replace(/\s+/g, '').split('::').at(-1) === symbol)?.value);
              if (mapped.length && mapped.every(value => typeof value === 'string')) replacement = definition.nativeType === 'coEnums' ? mapped : mapped[0];
            }
          }
          if (/^new ConfigOption(?:Point|Points|PointsGroups)/.test(expression.trim())) {
            const points = [...expression.matchAll(/Vec2d\s*\(([^)]+)\)/g)].map(match => split(match[1]).map(value => literal(value, constants)));
            if (points.every(point => point.length === 2 && point.every(value => typeof value === 'number'))) {
              if (definition.nativeType === 'coPoint') replacement = points[0] || [0, 0];
              else if (definition.nativeType === 'coPoints' || definition.nativeType === 'coPointsGroups') replacement = points;
            }
          } else if (/^new ConfigOption(?:Floats|Percents|Ints|Bools)Nullable\s*\{\s*ConfigOption\w+Nullable::nil_value\(\)\s*\}$/.test(expression.trim())) replacement = [null];
          if (replacement !== undefined) { definition.default = replacement; definition.unresolved = definition.unresolved.filter(item => item.field !== 'default'); }
        }
      }
      definitions.set(key, definition);
    }
  }
  // Native motion defaults are generated by a literal AxisDefault table.
  const axisTable = source.match(/std::vector<AxisDefault>\s+axes\s*\{/);
  if (!axisTable) throw new Error('Missing native AxisDefault table');
  const rows = literal('{' + balanced(source, axisTable.index + axisTable[0].lastIndexOf('{')).text + '}');
  const loopStart = source.indexOf('for (const AxisDefault &axis : axes)');
  const loop = balanced(source, source.indexOf('{', loopStart));
  const dynamicCalls = [...loop.text.matchAll(/def\s*=\s*this->add\s*\(/g)];
  for (const [axis, max_feedrate, max_acceleration, max_jerk] of rows) {
    for (let index = 0; index < dynamicCalls.length; index++) {
      const match = dynamicCalls[index], call = balanced(loop.text, match.index + match[0].lastIndexOf('(')), args = split(call.text);
      const prefix = args[0].match(/^("[^"\n]+")\s*\+\s*axis\.name$/);
      if (!prefix) throw new Error('Unknown native AxisDefault key expression');
      const key = literal(prefix[1]) + axis;
      const body = loop.text.slice(call.end, dynamicCalls[index + 1]?.index ?? loop.text.length).replace(/\(boost::format\(("[^"\n]*")\)\s*%\s*axis_upper\)\.str\(\)/g, (_, format) => JSON.stringify(literal(format).replaceAll('%1%', axis.toUpperCase())));
      const { definition } = metadataBlock(body, key, args[1], { ...context, constants: { ...context.constants, 'axis.max_feedrate': max_feedrate, 'axis.max_acceleration': max_acceleration, 'axis.max_jerk': max_jerk } });
      if (definition.default.length === 1 && Array.isArray(definition.default[0])) definition.default = definition.default[0];
      definition.source = { file: 'PrintConfig.cpp', line: lineAt(source, source.indexOf('{', loopStart) + 1 + match.index) };
      definitions.set(key, definition);
    }
  }
  const sourceLine = lineAt(source, source.indexOf('def = this->add_nullable(opt_key'));
  for (const key of stringList(source, 'filament_extruder_override_keys')) {
    const base = definitions.get(key.replace(/^filament_/, ''));
    if (!base) throw new Error(`Missing dynamic native override base: ${key}`);
    definitions.set(key, { ...structuredClone(base), key, nullable: true, mode: ['filament_retraction_length', 'filament_z_hop', 'filament_long_retractions_when_cut', 'filament_retraction_distances_when_cut'].includes(key) ? 'comSimple' : 'comAdvanced', source: { file: 'PrintConfig.cpp', line: sourceLine }, derivedFrom: base.key });
  }
  const materials = functionBlock(cleaned['MaterialType.cpp'], 'MaterialType::all()');
  const materialTable = materials.text.match(/material_types\s*=\s*\{/);
  if (!materialTable) throw new Error('Missing native material type database');
  const materialRows = literal('{' + balanced(materials.text, materialTable.index + materialTable[0].lastIndexOf('{')).text + '}');
  if (!Array.isArray(materialRows) || materialRows.some(row => !Array.isArray(row) || typeof row[0] !== 'string')) throw new Error('Unresolved native material types');
  const filamentType = definitions.get('filament_type');
  filamentType.options = materialRows.map(row => ({ value: row[0], label: row[0] }));
  filamentType.unresolved = filamentType.unresolved.filter(item => item.field !== 'enum_values');
  filamentType.optionsSource = { file: 'MaterialType.cpp', line: lineAt(cleaned['MaterialType.cpp'], materials.start + materialTable.index) };
  return definitions;
}

function layoutFrom(source, scope) {
  const layout = new Map(); let page = '', group = '', order = 0;
  function add(key, offset) { if (typeof key === 'string' && !layout.has(key)) layout.set(key, { page, group, order: order++, line: lineAt(source, offset) }); }
  function visit(signature) {
    const block = functionBlock(source, signature), variables = {};
    for (const match of block.text.matchAll(/const\s+std::vector<std::string>\s+(\w+)\s*\{/g)) variables[match[1]] = split(balanced(block.text, match.index + match[0].lastIndexOf('{')).text).map(value => literal(value));
    const loops = [];
    for (const match of block.text.matchAll(/for\s*\(\s*const\s+std::string\s*&?\s*(\w+)\s*:\s*/g)) {
      const parens = balanced(block.text, block.text.indexOf('(', match.index));
      const expression = parens.text.slice(parens.text.indexOf(':', parens.text.indexOf(match[1]) + match[1].length) + 1).trim();
      const values = expression.startsWith('{') ? split(expression.slice(1, -1)).map(value => literal(value)) : variables[expression];
      const rest = block.text.slice(parens.end), begin = parens.end + rest.search(/\S/);
      const end = block.text[begin] === '{' ? balanced(block.text, begin).end : block.text.indexOf(';', begin) + 1;
      if (values?.every(value => typeof value === 'string')) loops.push({ variable: match[1], values, begin, end });
    }
    const events = /add_options_page\s*\(|new_optgroup\s*\(|append_single_option_line\s*\(|get_option\s*\(|create_line_with_widget\s*\(|append_option_line\s*\(|append_retraction_option\s*\(|append_ironing_option\s*\(|add_filament_overrides_page\s*\(/g;
    for (const match of block.text.matchAll(events)) {
      const name = match[0].replace(/\s*\($/, '');
      if (name === 'add_filament_overrides_page') { const originalPage = page, originalGroup = group; visit('void TabFilament::add_filament_overrides_page()'); page = originalPage; group = originalGroup; continue; }
      const args = split(balanced(block.text, match.index + match[0].lastIndexOf('(')).text);
      const expression = args[name === 'create_line_with_widget' || name === 'append_option_line' ? 1 : 0] || '';
      let value = literal(expression);
      if (name === 'add_options_page' && expression === 'page_name' && block.text.includes('wxString::Format("Extruder")')) value = 'Extruder';
      if (name === 'add_options_page') { if (typeof value === 'string') page = value; group = ''; }
      else if (name === 'new_optgroup') { if (typeof value === 'string') group = value; }
      else if (typeof value === 'string') add(value, block.start + match.index);
      else {
        const loop = loops.find(loop => match.index >= loop.begin && match.index < loop.end);
        if (!loop) continue;
        if (expression === loop.variable) for (const key of loop.values) add(key, block.start + match.index);
        else {
          const concat = expression.match(/^\s*("(?:\\.|[^"\\])*")\s*\+\s*(\w+)\s*$/);
          if (concat && concat[2] === loop.variable) for (const suffix of loop.values) add(literal(concat[1]) + suffix, block.start + match.index);
        }
      }
    }
  }
  if (scope === 'filament') visit('void TabFilament::build()');
  else { visit('void TabPrinter::build_fff()'); visit('PageShp TabPrinter::build_kinematics_page()'); visit('void TabPrinter::build_unregular_pages('); }
  return layout;
}

export function extractProfileSchema(sources, provenance) {
  const cleaned = Object.fromEntries(Object.entries(sources).map(([name, source]) => [name, stripComments(source)]));
  const definitions = definitionsFrom(cleaned), validation = positiveValidationRules(cleaned['PrintConfig.cpp']);
  const keys = {
    machine: [...new Set([...stringList(cleaned['Preset.cpp'], 's_Preset_printer_options'), ...stringList(cleaned['Preset.cpp'], 's_Preset_machine_limits_options'), ...stringList(cleaned['PrintConfig.cpp'], 'm_extruder_option_keys')])],
    filament: stringList(cleaned['Preset.cpp'], 's_Preset_filament_options')
  };
  const scopes = {};
  for (const scope of ['machine', 'filament']) {
    const layout = layoutFrom(cleaned['Tab.cpp'], scope);
    const missing = keys[scope].filter(key => !definitions.has(key));
    if (missing.length) throw new Error(`Missing native ${scope} definitions: ${missing.join(', ')}`);
    const options = keys[scope].map(key => ({ ...definitions.get(key), scope, ...(validation.get(key) || {}), ...(layout.has(key) ? { ui: layout.get(key) } : {}), dependencyReferences: [...dependencyReferences(cleaned['ConfigManipulation.cpp'], key), ...dependencyReferences(cleaned['Tab.cpp'], key).map(reference => ({ ...reference, source: 'Tab.cpp' }))] }));
    scopes[scope] = { coverage: { nativeKeys: keys[scope].length, definitions: options.length, nativeUiControls: options.filter(item => item.ui).length, fullyParsed: options.filter(item => item.unresolved.length === 0).length, unresolved: options.filter(item => item.unresolved.length).map(item => ({ key: item.key, fields: item.unresolved })) }, options };
  }
  return { schemaVersion: 1, provenance, scope: 'FFF machine and filament preset keys declared by Preset.cpp, including native extruder keys and inherited nullable filament overrides.', dependencyStatus: 'Metadata and source references only. Dynamic page insertion, conditional visibility, enablement, and automatic corrections require separate implementation.', ...scopes };
}

export function extractProjectSchema(sources, provenance) {
  const cleaned = Object.fromEntries(Object.entries(sources).map(([name, source]) => [name, stripComments(source)]));
  const definitions = definitionsFrom(cleaned);
  const keys = ['bbl_calib_mark_logo', 'curr_bed_type', 'extruder_ams_count', 'filament_colour', 'filament_colour_type', 'filament_multi_colour', 'filament_ids', 'filament_map', 'filament_map_mode', 'filament_self_index', 'filament_settings_id', 'first_layer_print_sequence', 'flush_multiplier', 'flush_volumes_matrix', 'flush_volumes_vector', 'has_scarf_joint_seam', 'nozzle_volume_type', 'other_layers_print_sequence', 'other_layers_print_sequence_nums', 'start_end_points', 'wipe_tower_x', 'wipe_tower_y', 'print_settings_id', 'printer_settings_id'];
  if (keys.some(key => !definitions.has(key))) throw new Error('A requested native project definition is missing');
  const options = keys.map(key => definitions.get(key));
  return { schemaVersion: 1, provenance, scope: 'Source metadata for additional project settings observed in an OrcaSlicer 2.4.2 native project export; this is not a complete project option membership catalog.', options, coverage: { definitions: options.length, unresolved: options.filter(option => option.unresolved.length).map(option => ({ key: option.key, fields: option.unresolved })) } };
}
